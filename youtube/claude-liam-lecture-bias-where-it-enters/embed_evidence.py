#!/usr/bin/env python3
"""embed_evidence.py — Gate A copies ONLY scenes.py into its sandbox, so evidence/evidence.json is embedded in scenes.py
between the EV-BEGIN / EV-END markers (histogram samples trimmed to 160 per row). Re-run after evidence.py changes."""
import json, re
from pathlib import Path
HERE = Path(__file__).resolve().parent
ev = json.loads((HERE / "evidence/evidence.json").read_text())
for r in ev["A"]["rows"]:
    r["samples"] = r["samples"][:160]
blob = json.dumps(ev, separators=(",", ":"))
s = (HERE / "scenes.py").read_text()
new = "# EV-BEGIN (generated by embed_evidence.py from evidence/evidence.json)\nEV = _json.loads(r'''" + blob + "''')\n# EV-END"
if "# EV-BEGIN" in s:
    s = re.sub(r"# EV-BEGIN.*?# EV-END", lambda m: new, s, flags=re.S)
else:
    s = re.sub(r"try:\n    EV = _json.load\(open\(_os.path.join\(_HERE, \"evidence\", \"evidence.json\"\)\)\)\nexcept Exception:\n    EV = \{\}", lambda m: new, s)
(HERE / "scenes.py").write_text(s)
print("embedded", len(blob), "bytes")
